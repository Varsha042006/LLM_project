def clean_markdown_for_text(md_text: str) -> str:
    """Removes markdown syntax to produce readable plain text."""
    text = md_text
    # Remove image links
    text = re.sub(r'!\[.*?\]\(.*?\)', '', text)
    # Convert markdown links [text](url) to text (url)
    text = re.sub(r'\[(.*?)\]\((.*?)\)', r'\1 (\2)', text)
    # Remove code block fences
    text = re.sub(r'```[a-zA-Z]*\n', '', text)
    text = re.sub(r'```', '', text)
    # Remove inline code backticks
    text = re.sub(r'`([^`]+)`', r'\1', text)
    # Remove bold and italic markers
    text = re.sub(r'[*_~]{1,3}(.*?)[*_~]{1,3}', r'\1', text)
    # Remove header hashes
    text = re.sub(r'^#{1,6}\s*', '', text, flags=re.MULTILINE)
    # Remove blockquotes
    text = re.sub(r'^>\s*', '', text, flags=re.MULTILINE)
    return text.strip()


def extract_document_title(md_text: str, fallback_title: str = "Document") -> str:
    """Extracts the first H1/H2 header or clean first line as the document title."""
    for line in md_text.splitlines():
        line = line.strip()
        if line.startswith("# "):
            return line.replace("# ", "").strip()
        if line.startswith("## "):
            return line.replace("## ", "").strip()
        if line.startswith("**Title:") or line.startswith("**Document Title:"):
            return re.sub(r'\*\*(?:Document )?Title:\*\*\s*', '', line).strip()
    return fallback_title


class ProfessionalPDF(FPDF):
    """Custom FPDF subclass with modern headers, footers, and page numbers."""
    def __init__(self, doc_title: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.doc_title = doc_title[:45]
        self.set_auto_page_break(auto=True, margin=20)

    def header(self):
        if self.page_no() > 1:
            self.set_font("Helvetica", "I", 8)
            self.set_text_color(130, 140, 150)
            self.cell(0, 8, f"VYNEXA AI Platform  |  {self.doc_title}", border=0, align="L")
            self.line(15, 16, 195, 16)
            self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(140, 150, 160)
        self.line(15, 282, 195, 282)
        # Left: date, Right: page number
        now_str = datetime.now().strftime("%B %d, %Y")
        self.cell(90, 8, f"Generated on {now_str}", border=0, align="L")
        self.cell(90, 8, f"Page {self.page_no()} of {{nb}}", border=0, align="R")


def generate_pdf(title: str, markdown_content: str) -> bytes:
    """
    Generates a beautifully styled, high-quality PDF document from Markdown.
    Includes headers, styled bullet points, code blocks, and metadata cards.
    """
    clean_title = extract_document_title(markdown_content, title)
    pdf = ProfessionalPDF(doc_title=clean_title)
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_margins(15, 18, 15)

    # 1. Document Title Header
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(20, 30, 50)
    pdf.multi_cell(0, 10, clean_title.encode('latin-1', 'replace').decode('latin-1'), align="L")
    pdf.ln(2)

    # 2. Metadata / Subtitle Banner
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(100, 115, 130)
    gen_time = datetime.now().strftime("%Y-%m-%d %H:%M")
    pdf.cell(0, 6, f"Generated by VYNEXA Intelligent AI Platform  |  {gen_time}", ln=True, align="L")
    
    # Decorative rule
    pdf.set_draw_color(16, 163, 127) # Emerald accent
    pdf.set_line_width(0.8)
    pdf.line(15, pdf.get_y() + 2, 195, pdf.get_y() + 2)
    pdf.ln(6)

    # 3. Content Parsing & Rendering
    lines = markdown_content.splitlines()
    in_code_block = False
    code_block_lines = []

    for line in lines:
        stripped = line.strip()

        # Handle Code Blocks
        if stripped.startswith("```"):
            if in_code_block:
                # End of code block: render box
                in_code_block = False
                pdf.set_fill_color(245, 247, 250)
                pdf.set_text_color(40, 50, 60)
                pdf.set_font("Courier", "", 8.5)
                pdf.set_draw_color(220, 226, 235)
                for cl in code_block_lines:
                    safe_cl = cl.encode('latin-1', 'replace').decode('latin-1')
                    pdf.cell(0, 5, "   " + safe_cl, ln=True, fill=True)
                pdf.ln(3)
                code_block_lines = []
            else:
                in_code_block = True
                code_block_lines = []
            continue

        if in_code_block:
            code_block_lines.append(line)
            continue

        if not stripped:
            pdf.ln(2)
            continue

        # Skip duplicate title header if already rendered
        if (stripped.startswith("# ") or stripped.startswith("## ")) and clean_title.lower() in stripped.lower():
            continue

        # Headings
        if stripped.startswith("### "):
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(20, 40, 80)
            h_text = stripped.replace("### ", "").replace("**", "")
            pdf.multi_cell(0, 7, h_text.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(1)
        elif stripped.startswith("## "):
            pdf.ln(4)
            pdf.set_font("Helvetica", "B", 14)
            pdf.set_text_color(15, 30, 65)
            h_text = stripped.replace("## ", "").replace("**", "")
            pdf.multi_cell(0, 8, h_text.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(1.5)
        elif stripped.startswith("# "):
            pdf.ln(5)
            pdf.set_font("Helvetica", "B", 16)
            pdf.set_text_color(10, 25, 55)
            h_text = stripped.replace("# ", "").replace("**", "")
            pdf.multi_cell(0, 9, h_text.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(2)

        # Bullet Points
        elif stripped.startswith("* ") or stripped.startswith("- ") or stripped.startswith("• "):
            bullet_text = re.sub(r'^[*•-]\s*', '', stripped)
            # Remove markdown bold
            bullet_clean = re.sub(r'\*\*(.*?)\*\*', r'\1', bullet_text)
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(35, 45, 55)
            # Indent bullet
            pdf.cell(6, 6, chr(149), ln=0, align="R") # bullet symbol
            pdf.multi_cell(0, 6, " " + bullet_clean.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(0.5)

        # Numbered list
        elif re.match(r'^\d+\.\s+', stripped):
            num_match = re.match(r'^(\d+\.)\s*(.*)', stripped)
            num_str = num_match.group(1)
            item_text = re.sub(r'\*\*(.*?)\*\*', r'\1', num_match.group(2))
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(20, 40, 80)
            pdf.cell(8, 6, num_str, ln=0, align="R")
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(35, 45, 55)
            pdf.multi_cell(0, 6, " " + item_text.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(0.5)

        # Horizontal separator
        elif stripped in ["---", "***", "___"]:
            pdf.set_draw_color(225, 230, 238)
            pdf.set_line_width(0.4)
            pdf.line(15, pdf.get_y() + 2, 195, pdf.get_y() + 2)
            pdf.ln(4)

        # Standard paragraph
        else:
            para_text = re.sub(r'\*\*(.*?)\*\*', r'\1', stripped)
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(35, 45, 55)
            pdf.multi_cell(0, 5.8, para_text.encode('latin-1', 'replace').decode('latin-1'))
            pdf.ln(1)

    return bytes(pdf.output())


def generate_docx(title: str, markdown_content: str) -> bytes:
    """
    Generates a Microsoft Word (.docx) document formatted with executive typography,
    styled headings, bullet lists, code callouts, and metadata headers.
    """
    clean_title = extract_document_title(markdown_content, title)
    doc = Document()

    # Configure Margins
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)

    # Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run(clean_title)
    title_run.font.size = Pt(22)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(20, 35, 60)
    title_p.paragraph_format.space_after = Pt(2)

    # Subtitle / Metadata
    sub_p = doc.add_paragraph()
    sub_run = sub_p.add_run(f"VYNEXA Intelligent AI Platform  |  {datetime.now().strftime('%B %d, %Y')}")
    sub_run.font.size = Pt(9.5)
    sub_run.font.italic = True
    sub_run.font.color.rgb = RGBColor(120, 130, 145)
    sub_p.paragraph_format.space_after = Pt(14)

    lines = markdown_content.splitlines()
    in_code_block = False
    code_block_lines = []

    for line in lines:
        stripped = line.strip()

        # Handle Code Blocks
        if stripped.startswith("```"):
            if in_code_block:
                in_code_block = False
                code_text = "\n".join(code_block_lines)
                code_p = doc.add_paragraph()
                code_p.paragraph_format.left_indent = Inches(0.3)
                code_p.paragraph_format.space_before = Pt(4)
                code_p.paragraph_format.space_after = Pt(8)
                run = code_p.add_run(code_text)
                run.font.name = "Consolas"
                run.font.size = Pt(9)
                run.font.color.rgb = RGBColor(40, 50, 60)
                code_block_lines = []
            else:
                in_code_block = True
                code_block_lines = []
            continue

        if in_code_block:
            code_block_lines.append(line)
            continue

        if not stripped:
            continue

        if (stripped.startswith("# ") or stripped.startswith("## ")) and clean_title.lower() in stripped.lower():
            continue

        # Headings
        if stripped.startswith("# "):
            h = doc.add_heading(level=1)
            r = h.add_run(stripped.replace("# ", "").replace("**", ""))
            r.font.size = Pt(16)
            r.font.bold = True
            r.font.color.rgb = RGBColor(15, 30, 60)
        elif stripped.startswith("## "):
            h = doc.add_heading(level=2)
            r = h.add_run(stripped.replace("## ", "").replace("**", ""))
            r.font.size = Pt(13)
            r.font.bold = True
            r.font.color.rgb = RGBColor(25, 45, 80)
        elif stripped.startswith("### "):
            h = doc.add_heading(level=3)
            r = h.add_run(stripped.replace("### ", "").replace("**", ""))
            r.font.size = Pt(11.5)
            r.font.bold = True
            r.font.color.rgb = RGBColor(35, 60, 100)

        # Bullets
        elif stripped.startswith("* ") or stripped.startswith("- ") or stripped.startswith("• "):
            bullet_text = re.sub(r'^[*•-]\s*', '', stripped)
            bp = doc.add_paragraph(style='List Bullet')
            # Parse bold spans
            parts = re.split(r'(\*\*.*?\*\*)', bullet_text)
            for part in parts:
                if part.startswith("**") and part.endswith("**"):
                    r = bp.add_run(part[2:-2])
                    r.bold = True
                else:
                    bp.add_run(part)
            bp.paragraph_format.space_after = Pt(2)

        # Numbered list
        elif re.match(r'^\d+\.\s+', stripped):
            num_match = re.match(r'^\d+\.\s*(.*)', stripped)
            np = doc.add_paragraph(style='List Number')
            item_text = num_match.group(1)
            parts = re.split(r'(\*\*.*?\*\*)', item_text)
            for part in parts:
                if part.startswith("**") and part.endswith("**"):
                    r = np.add_run(part[2:-2])
                    r.bold = True
                else:
                    np.add_run(part)
            np.paragraph_format.space_after = Pt(2)

        # Regular Paragraph
        else:
            p = doc.add_paragraph()
            parts = re.split(r'(\*\*.*?\*\*)', stripped)
            for part in parts:
                if part.startswith("**") and part.endswith("**"):
                    r = p.add_run(part[2:-2])
                    r.bold = True
                else:
                    p.add_run(part)
            p.paragraph_format.space_after = Pt(6)

    output = io.BytesIO()
    doc.save(output)
    output.seek(0)
    return output.getvalue()


def generate_markdown(title: str, content: str) -> str:
    """Formats markdown with standard publication headers."""
    clean_title = extract_document_title(content, title)
    header = (
        f"# {clean_title}\n\n"
        f"*Generated by VYNEXA AI Platform on {datetime.now().strftime('%B %d, %Y at %I:%M %p')}*\n\n"
        f"---\n\n"
    )
    if clean_title.lower() in content.lower():
        return header + content
    return header + content


def generate_txt(title: str, content: str) -> str:
    """Produces clean plaintext formatted document."""
    clean_title = extract_document_title(content, title)
    plain = clean_markdown_for_text(content)
    divider = "=" * min(len(clean_title) + 10, 70)
    header = (
        f"{divider}\n"
        f"{clean_title.upper()}\n"
        f"Generated by VYNEXA AI Platform  |  {datetime.now().strftime('%Y-%m-%d %H:%M')}\n"
        f"{divider}\n\n"
    )
    return header + plain
